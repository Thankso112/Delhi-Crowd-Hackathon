"""Step 1: load the ticket CSV with pandas, clean it, and profile it."""
import numpy as np, pandas as pd
from crowd.text import config

def load_tickets(path=None) -> pd.DataFrame:
    """Read tickets.csv in chunks (low memory) -> tidy DataFrame. Real file notes: values are quoted, missing values are the text NULL,
    timestamps look like 2026-10-28 10:19:18.780611+05:30, is_ac is True/False, and about half of vehicle_number is NULL."""
    C = config.COL
    inv = {v: k for k, v in C.items()}
    path = path or config.TICKETS_CSV
    head = pd.read_csv(path, nrows=0).columns
    missing = [v for v in C.values() if v not in head]
    assert not missing, f"Columns missing from the CSV: {missing}. Edit config.COL. Found: {list(head)}"
    parts = []
    for ch in pd.read_csv(path, usecols=list(C.values()), na_values=["NULL", "null", "None", ""], chunksize=400_000,
                          dtype={C["vehicle"]: str, C["route"]: str, C["start"]: str, C["end"]: str, C["ttype"]: str, C["ac"]: str}):
        ch = ch.rename(columns=inv)
        out = pd.DataFrame({
            "pax": pd.to_numeric(ch.pax, errors="coerce"),
            "amount": pd.to_numeric(ch.amount, errors="coerce").astype("float32"),
            "vehicle": ch.vehicle, "ttype": ch.ttype, "start_name": ch.start, "end_name": ch.end, "route_raw": ch.route,
            # keep the local (IST) clock time: first 19 characters 'YYYY-MM-DD HH:MM:SS'; ignore microseconds and the +05:30 suffix
            "ts": pd.to_datetime(ch.ts.astype(str).str.strip().str.slice(0, 19), errors="coerce"),
            "is_ac": ch.ac.astype(str).str.lower().isin(["1", "true", "t", "yes", "y", "ac"]).astype("int8"),
        })
        out = out[out.ts.notna() & out.route_raw.notna() & (out.pax > 0)]
        out["pax"] = out.pax.astype("int8")
        for c in ["vehicle", "ttype", "route_raw", "start_name", "end_name"]:
            out[c] = out[c].astype("category")
        parts.append(out)
    df = pd.concat(parts, ignore_index=True)
    df["date"] = df.ts.dt.date.astype(str)
    df["hour"] = df.ts.dt.hour.astype("int8")
    df["dow"] = (df.ts.dt.dayofweek + 1).astype("int8")      # Monday=1 ... Sunday=7
    return df

def profile(df: pd.DataFrame) -> dict:
    """Basic data-quality tables: used by notebook 01 and written to docs/data_profile.md."""
    daily = df.groupby("date").agg(tickets=("pax", "size"), pax=("pax", "sum"), dow=("dow", "first")).reset_index()
    wk = daily[daily.dow < 6].pax                       # judge weekdays against weekdays only (weekends are naturally lower)
    med = wk.median(); mad = (wk - med).abs().median()
    daily["outlier"] = (daily.dow < 6) & ((daily.pax - med).abs() > 3.5 * 1.4826 * max(mad, 1))
    return dict(
        n_rows=len(df), date_range=(df.ts.min(), df.ts.max()),
        missing_start=int(df.start_name.isna().sum()), missing_end=int(df.end_name.isna().sum()), missing_vehicle=int(df.vehicle.isna().sum()),
        duplicates=0, daily=daily,
        ticket_types=df.groupby("ttype", observed=True).agg(n=("pax", "size"), share_zero_amount=("amount", lambda s: float((s == 0).mean())), avg_pax=("pax", "mean")).reset_index(),
        pax_counts=df.pax.value_counts().sort_index().head(12).rename_axis("pax").reset_index(name="n"),
        ac_split=df.is_ac.value_counts().rename_axis("is_ac").reset_index(name="n"),
        hourly=df.groupby("hour").pax.sum().div(df.date.nunique()).round().rename("avg_pax_per_day").reset_index())

def profile_markdown(p: dict, source) -> str:
    return f"""# Ticket data profile (generated by crowd.ingest.profile)
- Source: `{source}`
- Rows kept (valid time, route, pax>0): {p['n_rows']:,}
- Date range: {p['date_range'][0]} to {p['date_range'][1]}
- Missing start stop: {p['missing_start']:,}; missing end stop: {p['missing_end']:,}; missing vehicle_number: {p['missing_vehicle']:,}; exact duplicate rows: {p['duplicates']:,}
- Outlier weekdays: {', '.join(p['daily'][p['daily'].outlier].date) or 'none'}

## Ticket types (is amount == 0 a free ride?)
{p['ticket_types'].to_markdown(index=False)}

## passenger_count values
{p['pax_counts'].to_markdown(index=False)}

## AC split
{p['ac_split'].to_markdown(index=False)}

## Average passengers per hour of day
{p['hourly'].to_markdown(index=False)}
"""
